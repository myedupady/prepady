/**
 * AI controls + spend tracking, persisted in the `ai-controls` Payload global so
 * admins can see usage and flip the kill switch / budget from the admin panel.
 *
 * The global is the source of truth for operational controls; environment vars
 * provide the defaults used when the global is unset or unreadable (e.g. before
 * the first admin save, or in a script with a stale schema).
 */

import type { Payload } from 'payload'
import { roundUsd } from './pricing'
import type { AICallKind, AIProviderName } from './types'

const GLOBAL_SLUG = 'ai-controls'

export interface AIControls {
  provider: AIProviderName
  autoGenerateExplanations: boolean
  monthlyBudgetUsd: number
  paused: boolean
}

export interface AIUsageSnapshot {
  currentMonth: string
  spendUsd: number
  explainCount: number
  followupCount: number
  markCount: number
  autoGeneratedCount: number
}

const envBool = (v: string | undefined, dflt: boolean): boolean =>
  v == null ? dflt : /^(1|true|yes|on)$/i.test(v.trim())

const envNum = (v: string | undefined, dflt: number): number => {
  const n = Number(v)
  return Number.isFinite(n) && n >= 0 ? n : dflt
}

export const DEFAULT_CONTROLS: AIControls = {
  provider: (process.env.AI_PROVIDER as AIProviderName) || 'anthropic',
  autoGenerateExplanations: envBool(process.env.AI_AUTOGEN_ON_PUBLISH, true),
  monthlyBudgetUsd: envNum(process.env.AI_MONTHLY_BUDGET_USD, 25),
  paused: envBool(process.env.AI_PAUSED, false),
}

/** UTC year-month key, e.g. "2026-10". */
export function monthKey(d = new Date()): string {
  return `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, '0')}`
}

type GlobalShape = {
  controls?: Partial<AIControls>
  usage?: Partial<AIUsageSnapshot>
}

async function readGlobal(payload: Payload): Promise<GlobalShape> {
  try {
    return (await payload.findGlobal({ slug: GLOBAL_SLUG, overrideAccess: true })) as GlobalShape
  } catch {
    return {}
  }
}

/** Operational controls, merged over env defaults. */
export async function getControls(payload: Payload): Promise<AIControls> {
  const g = await readGlobal(payload)
  const c = g.controls ?? {}
  return {
    provider: (c.provider as AIProviderName) ?? DEFAULT_CONTROLS.provider,
    autoGenerateExplanations: c.autoGenerateExplanations ?? DEFAULT_CONTROLS.autoGenerateExplanations,
    monthlyBudgetUsd:
      typeof c.monthlyBudgetUsd === 'number' ? c.monthlyBudgetUsd : DEFAULT_CONTROLS.monthlyBudgetUsd,
    paused: c.paused ?? DEFAULT_CONTROLS.paused,
  }
}

/** Current-month usage snapshot (zeroed if the stored month has rolled over). */
export async function getUsage(payload: Payload): Promise<AIUsageSnapshot> {
  const g = await readGlobal(payload)
  const u = g.usage ?? {}
  const now = monthKey()
  const fresh = u.currentMonth === now
  return {
    currentMonth: now,
    spendUsd: fresh ? (u.spendUsd ?? 0) : 0,
    explainCount: fresh ? (u.explainCount ?? 0) : 0,
    followupCount: fresh ? (u.followupCount ?? 0) : 0,
    markCount: fresh ? (u.markCount ?? 0) : 0,
    autoGeneratedCount: fresh ? (u.autoGeneratedCount ?? 0) : 0,
  }
}

/** True when this month's spend has reached the configured budget. */
export function isOverBudget(controls: AIControls, usage: AIUsageSnapshot): boolean {
  return controls.monthlyBudgetUsd > 0 && usage.spendUsd >= controls.monthlyBudgetUsd
}

const KIND_COUNTER: Record<AICallKind | 'autogen', keyof AIUsageSnapshot> = {
  explain: 'explainCount',
  followup: 'followupCount',
  mark: 'markCount',
  autogen: 'autoGeneratedCount',
}

/**
 * Record one call's cost + increment the relevant counter. Rolls the month over
 * automatically. Best-effort: never throws (a metering failure must not break a
 * student-facing response).
 */
export async function recordUsage(
  payload: Payload,
  entry: { kind: AICallKind | 'autogen'; costUsd: number },
): Promise<void> {
  try {
    const current = await getUsage(payload) // already month-rolled
    const next: AIUsageSnapshot = {
      ...current,
      spendUsd: roundUsd(current.spendUsd + Math.max(0, entry.costUsd)),
      [KIND_COUNTER[entry.kind]]: (current[KIND_COUNTER[entry.kind]] as number) + 1,
    }
    await payload.updateGlobal({ slug: GLOBAL_SLUG, overrideAccess: true, data: { usage: next } })
  } catch (err) {
    console.warn('[ai] recordUsage failed (non-fatal):', err)
  }
}
