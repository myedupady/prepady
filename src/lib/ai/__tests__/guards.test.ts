import { test } from 'node:test'
import assert from 'node:assert/strict'
import { guardLiveAI, resolveProvider } from '../index'
import { isOverBudget, type AIControls, type AIUsageSnapshot } from '../usage'
import { isAIError } from '../types'

const controls = (over: Partial<AIControls> = {}): AIControls => ({
  provider: 'anthropic',
  autoGenerateExplanations: true,
  monthlyBudgetUsd: 25,
  paused: false,
  ...over,
})

const usage = (over: Partial<AIUsageSnapshot> = {}): AIUsageSnapshot => ({
  currentMonth: '2026-10',
  spendUsd: 0,
  explainCount: 0,
  followupCount: 0,
  markCount: 0,
  autoGeneratedCount: 0,
  ...over,
})

test('isOverBudget: disabled when budget is 0', () => {
  assert.equal(isOverBudget(controls({ monthlyBudgetUsd: 0 }), usage({ spendUsd: 999 })), false)
})

test('isOverBudget: true only once spend reaches the cap', () => {
  assert.equal(isOverBudget(controls({ monthlyBudgetUsd: 25 }), usage({ spendUsd: 24.99 })), false)
  assert.equal(isOverBudget(controls({ monthlyBudgetUsd: 25 }), usage({ spendUsd: 25 })), true)
})

test('guardLiveAI throws not_configured when provider unavailable', () => {
  assert.throws(
    () => guardLiveAI({ controls: controls(), usage: usage(), providerConfigured: false }),
    (e) => isAIError(e) && e.code === 'not_configured',
  )
})

test('guardLiveAI throws paused when kill switch on', () => {
  assert.throws(
    () => guardLiveAI({ controls: controls({ paused: true }), usage: usage(), providerConfigured: true }),
    (e) => isAIError(e) && e.code === 'paused',
  )
})

test('guardLiveAI throws budget_exceeded when over cap', () => {
  assert.throws(
    () => guardLiveAI({ controls: controls(), usage: usage({ spendUsd: 100 }), providerConfigured: true }),
    (e) => isAIError(e) && e.code === 'budget_exceeded',
  )
})

test('guardLiveAI passes when configured, unpaused, under budget', () => {
  assert.doesNotThrow(() => guardLiveAI({ controls: controls(), usage: usage({ spendUsd: 1 }), providerConfigured: true }))
})

test('resolveProvider throws when no key is set', () => {
  const saved = process.env.ANTHROPIC_API_KEY
  delete process.env.ANTHROPIC_API_KEY
  try {
    assert.throws(() => resolveProvider({ provider: 'anthropic' }), (e) => isAIError(e) && e.code === 'not_configured')
  } finally {
    if (saved !== undefined) process.env.ANTHROPIC_API_KEY = saved
  }
})

test('resolveProvider returns anthropic when a key is present', () => {
  const saved = process.env.ANTHROPIC_API_KEY
  process.env.ANTHROPIC_API_KEY = 'sk-ant-test-placeholder'
  try {
    const p = resolveProvider({ provider: 'anthropic' })
    assert.equal(p.name, 'anthropic')
  } finally {
    if (saved === undefined) delete process.env.ANTHROPIC_API_KEY
    else process.env.ANTHROPIC_API_KEY = saved
  }
})

test('resolveProvider falls back to anthropic when gemini is chosen but unconfigured', () => {
  const saved = process.env.ANTHROPIC_API_KEY
  process.env.ANTHROPIC_API_KEY = 'sk-ant-test-placeholder'
  try {
    const p = resolveProvider({ provider: 'gemini' })
    assert.equal(p.name, 'anthropic')
  } finally {
    if (saved === undefined) delete process.env.ANTHROPIC_API_KEY
    else process.env.ANTHROPIC_API_KEY = saved
  }
})
