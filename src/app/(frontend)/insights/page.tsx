import type { Metadata } from 'next'
import { redirect } from 'next/navigation'
import Link from 'next/link'
import { getPayload } from 'payload'
import type { Where, CollectionSlug } from 'payload'
import { getAuthContext } from '@/lib/auth'
import {
  GraduationCap, ArrowLeft, Users, FileText, Layers, Activity, Sparkles, DollarSign, Database,
} from 'lucide-react'
import { Card, CardContent } from '@/components/ui/card'
import { RadialProgress, BarList, type BarItem } from '@/components/charts/Charts'

export const metadata: Metadata = { title: 'Insights — Prepady Admin' }
export const dynamic = 'force-dynamic'

async function countWhere(payload: Awaited<ReturnType<typeof getPayload>>, collection: CollectionSlug, where: Where) {
  const r = await payload.count({ collection, where, overrideAccess: true }).catch(() => ({ totalDocs: 0 }))
  return r.totalDocs ?? 0
}

export default async function InsightsPage() {
  const { payload, user } = await getAuthContext()
  if (!user) redirect('/login?redirect=/insights')
  if ((user as { role?: string }).role !== 'admin') redirect('/dashboard')

  const [
    usersTotal, admins, questionsTotal, mcq, theory, published, withExplanation,
    exams, subjects, topics, sessionsTotal, completedSessions, premiumUsers, media,
  ] = await Promise.all([
    countWhere(payload, 'users', {}),
    countWhere(payload, 'users', { role: { equals: 'admin' } }),
    countWhere(payload, 'questions', {}),
    countWhere(payload, 'questions', { questionType: { equals: 'mcq' } }),
    countWhere(payload, 'questions', { questionType: { equals: 'theory' } }),
    countWhere(payload, 'questions', { status: { equals: 'published' } }),
    countWhere(payload, 'questions', { explanation: { exists: true } }),
    countWhere(payload, 'exams', {}),
    countWhere(payload, 'subjects', {}),
    countWhere(payload, 'topics', {}),
    countWhere(payload, 'quiz-sessions', {}),
    countWhere(payload, 'quiz-sessions', { status: { equals: 'completed' } }),
    countWhere(payload, 'users', { plan: { equals: 'premium' } }),
    countWhere(payload, 'media', {}),
  ])

  const ai = (await payload.findGlobal({ slug: 'ai-controls', overrideAccess: true }).catch(() => ({}))) as {
    usage?: { spendUsd?: number; explainCount?: number; autoGeneratedCount?: number; followupCount?: number; markCount?: number; currentMonth?: string }
    controls?: { monthlyBudgetUsd?: number }
  }
  const usage = ai.usage ?? {}
  const budget = ai.controls?.monthlyBudgetUsd ?? 0
  const spend = usage.spendUsd ?? 0

  const pubPct = questionsTotal ? (published / questionsTotal) * 100 : 0
  const explPct = questionsTotal ? (withExplanation / questionsTotal) * 100 : 0

  const contentBars: BarItem[] = [
    { label: 'MCQ', pct: questionsTotal ? (mcq / questionsTotal) * 100 : 0, detail: String(mcq), tone: 'neutral' },
    { label: 'Theory', pct: questionsTotal ? (theory / questionsTotal) * 100 : 0, detail: String(theory), tone: 'fair' },
  ]
  const aiMax = Math.max(usage.explainCount ?? 0, usage.autoGeneratedCount ?? 0, usage.followupCount ?? 0, usage.markCount ?? 0, 1)
  const aiBars: BarItem[] = [
    { label: 'Auto-generated explanations', pct: ((usage.autoGeneratedCount ?? 0) / aiMax) * 100, detail: String(usage.autoGeneratedCount ?? 0), tone: 'good' },
    { label: 'On-demand explanations', pct: ((usage.explainCount ?? 0) / aiMax) * 100, detail: String(usage.explainCount ?? 0), tone: 'neutral' },
    { label: 'Follow-ups', pct: ((usage.followupCount ?? 0) / aiMax) * 100, detail: String(usage.followupCount ?? 0), tone: 'fair' },
    { label: 'Essays marked', pct: ((usage.markCount ?? 0) / aiMax) * 100, detail: String(usage.markCount ?? 0), tone: 'weak' },
  ]

  const tiles = [
    { label: 'Users', value: usersTotal, sub: `${premiumUsers} premium · ${admins} admin`, icon: Users },
    { label: 'Questions', value: questionsTotal, sub: `${mcq} MCQ · ${theory} theory`, icon: FileText },
    { label: 'Catalogue', value: exams, sub: `${subjects} subjects · ${topics} topics`, icon: Layers },
    { label: 'Quiz sessions', value: sessionsTotal, sub: `${completedSessions} completed`, icon: Activity },
    { label: 'AI spend (mo)', value: `$${spend.toFixed(2)}`, sub: budget ? `of $${budget} budget` : 'no cap', icon: DollarSign },
    { label: 'Media', value: media, sub: 'uploads', icon: Database },
  ]

  return (
    <main className="min-h-screen bg-background">
      <header className="sticky top-0 z-50 bg-background/90 backdrop-blur border-b border-border">
        <div className="max-w-5xl mx-auto px-6 h-16 flex items-center justify-between">
          <Link href="/" className="flex items-center gap-2 font-display font-extrabold text-lg text-ink-900">
            <GraduationCap className="w-6 h-6 text-gold-500" /> Prepady<span className="text-gold-500">.</span>
          </Link>
          <div className="flex items-center gap-4">
            <a href="/admin" className="text-sm font-semibold text-muted-foreground hover:text-ink-900">Admin panel</a>
            <Link href="/dashboard" className="inline-flex items-center gap-1.5 text-sm font-semibold text-muted-foreground hover:text-ink-900"><ArrowLeft className="w-4 h-4" /> Dashboard</Link>
          </div>
        </div>
      </header>

      <div className="max-w-5xl mx-auto px-6 py-10">
        <h1 className="font-display text-3xl font-extrabold text-ink-900 mb-1">Insights</h1>
        <p className="text-muted-foreground mb-8">Content, users, and AI usage at a glance.{usage.currentMonth ? ` AI figures for ${usage.currentMonth}.` : ''}</p>

        {/* Stat tiles */}
        <div className="grid grid-cols-2 md:grid-cols-3 gap-4 mb-8">
          {tiles.map(({ label, value, sub, icon: Icon }) => (
            <Card key={label} className="border border-border bg-card shadow-brand">
              <CardContent className="p-5">
                <div className="w-9 h-9 rounded-xl bg-gold-50 flex items-center justify-center mb-3"><Icon className="w-4 h-4 text-gold-600" /></div>
                <p className="text-2xl font-black text-ink-900">{value}</p>
                <p className="text-xs text-muted-foreground mt-0.5 font-medium">{label}</p>
                <p className="text-[11px] text-muted-foreground mt-1">{sub}</p>
              </CardContent>
            </Card>
          ))}
        </div>

        {/* Content readiness */}
        <div className="grid md:grid-cols-3 gap-4 mb-8">
          <Card className="border border-border bg-card shadow-brand">
            <CardContent className="p-5 flex flex-col items-center">
              <p className="self-start text-xs font-black uppercase tracking-widest text-muted-foreground mb-3">Published</p>
              <RadialProgress value={pubPct} sublabel={`${published}/${questionsTotal}`} tone="success" />
            </CardContent>
          </Card>
          <Card className="border border-border bg-card shadow-brand">
            <CardContent className="p-5 flex flex-col items-center">
              <p className="self-start text-xs font-black uppercase tracking-widest text-muted-foreground mb-3">With explanation</p>
              <RadialProgress value={explPct} sublabel={`${withExplanation}/${questionsTotal}`} tone="gold" />
            </CardContent>
          </Card>
          <Card className="border border-border bg-card shadow-brand">
            <CardContent className="p-5">
              <p className="text-xs font-black uppercase tracking-widest text-muted-foreground mb-4">Question types</p>
              <BarList items={contentBars} />
            </CardContent>
          </Card>
        </div>

        {/* AI usage */}
        <Card className="border border-border bg-card shadow-brand">
          <CardContent className="p-5">
            <p className="flex items-center gap-1.5 text-xs font-black uppercase tracking-widest text-muted-foreground mb-4"><Sparkles className="w-3.5 h-3.5" /> AI usage this month</p>
            <BarList items={aiBars} />
          </CardContent>
        </Card>
      </div>
    </main>
  )
}
